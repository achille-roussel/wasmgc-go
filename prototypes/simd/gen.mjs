// Generates kernels.wat: scalar vs SIMD strategies over GC byte arrays.
// Run: node gen.mjs && wasm-tools parse kernels.wat -o kernels.wasm

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const dir = dirname(fileURLToPath(import.meta.url));

function load16Nested(arrayLocal, baseLocal) {
  let expr = `(v128.const i64x2 0 0)`;
  for (let i = 0; i < 16; i++) {
    expr =
      `(i8x16.replace_lane ${i}\n` +
      `          ${expr}\n` +
      `          (array.get_u $bytes (local.get ${arrayLocal}) (i32.add (local.get ${baseLocal}) (i32.const ${i}))))`;
  }
  return expr;
}

function composeI64(arrayLocal, baseLocal) {
  const parts = [];
  for (let i = 0; i < 8; i++) {
    const shift = i * 8;
    parts.push(
      `(i64.shl (i64.extend_i32_u (array.get_u $bytes (local.get ${arrayLocal}) (i32.add (local.get ${baseLocal}) (i32.const ${i})))) (i64.const ${shift}))`
    );
  }
  return parts.reduce((a, b) => `(i64.or\n      ${a}\n      ${b})`);
}

function replaceLaneTable() {
  // For fill: poke one byte into a v128 by lane index using nested ifs.
  let body = `(local.get $v)`;
  for (let i = 15; i >= 0; i--) {
    body =
      `(if (result v128) (i32.eq (local.get $off) (i32.const ${i}))\n` +
      `          (then (i8x16.replace_lane ${i} (local.get $v) (local.get $needle)))\n` +
      `          (else ${body}))`;
  }
  return body;
}

