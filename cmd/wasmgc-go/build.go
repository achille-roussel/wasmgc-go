package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/achille-roussel/wasmgc-go/internal/pipeline"
)

func cmdBuild(args []string) int {
	fs := flag.NewFlagSet("build", flag.ExitOnError)
	out := fs.String("o", "", "output Wasm path (default: <name>.wasm)")
	target := fs.String("target", "node", "host target: node|browser")
	tags := fs.String("tags", "", "comma-separated build tags")
	names := fs.Bool("names", false, "emit Wasm name section")
	vetFail := fs.Bool("vet-fail", false, "treat int64→int conversion warnings as errors")
	goroot := fs.String("goroot", "", "override materialized GOROOT")
	skipStd := fs.Bool("skip-stdlib", false, "do not materialize GOROOT (programs with no std imports)")
	_ = fs.Parse(args)

	pkg := packageArg(fs)
	res, err := pipeline.Compile(pipeline.Options{
		Package:           pkg,
		Tags:              splitTags(*tags),
		Names:             *names,
		VetFail:           *vetFail,
		GOROOT:            *goroot,
		SkipStdlib:        *skipStd,
		SynthPrintRuntime: false, // std/src/runtime linked via rtlink
	})
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	printWarnings(res.Warnings)

	outPath := *out
	if outPath == "" {
		outPath = defaultOutName(pkg, res)
	}
	if dir := filepath.Dir(outPath); dir != "." && dir != "" {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			fmt.Fprintln(os.Stderr, err)
			return 1
		}
	}
	if err := os.WriteFile(outPath, res.Wasm, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	fmt.Println(outPath)

	switch *target {
	case "node", "browser":
		jsPath := outPath + ".js"
		if err := writeRunner(jsPath, outPath, *target); err != nil {
			fmt.Fprintln(os.Stderr, err)
			return 1
		}
		fmt.Println(jsPath)
	default:
		fmt.Fprintf(os.Stderr, "wasmgc-go build: unknown -target %q\n", *target)
		return 2
	}
	return 0
}

func defaultOutName(pkg string, res *pipeline.Result) string {
	if res != nil && res.Program != nil && res.Program.Main != nil {
		if dir := res.Program.Main.Dir; dir != "" {
			return filepath.Base(dir) + ".wasm"
		}
		base := filepath.Base(res.Program.Main.PkgPath)
		if base != "" && base != "." {
			return base + ".wasm"
		}
	}
	if pkg == "." || pkg == "" {
		return "prog.wasm"
	}
	return filepath.Base(pkg) + ".wasm"
}

func writeRunner(jsPath, wasmPath, target string) error {
	glue, err := findWasmgcJS()
	if err != nil {
		return err
	}
	absGlue, err := filepath.Abs(glue)
	if err != nil {
		return err
	}
	absWasm, err := filepath.Abs(wasmPath)
	if err != nil {
		return err
	}
	// Thin wrapper: call lib/wasmgc.js main() with the sibling wasm path.
	// Browser target uses the same glue; differences are inside wasmgc.js.
	_ = target
	src := fmt.Sprintf(`#!/usr/bin/env node
// generated by wasmgc-go build -target %s
import { pathToFileURL } from "node:url";

const wasmPath = %q;
const glueURL = pathToFileURL(%q).href;
const mod = await import(glueURL);
const rest = process.argv.slice(2);
process.argv = [process.argv[0], process.argv[1], wasmPath, ...rest];
await mod.main();
`, target, absWasm, absGlue)
	return os.WriteFile(jsPath, []byte(src), 0o755)
}
